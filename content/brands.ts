/**
 * CSS custom properties derived from the tokens. Applied on <html> so CSS
 * (Tailwind `bg-bg`, `text-fg`, `text-accent`) reads the same values as WebGL.
 */
export function themeCssVars(): Record<`--${string}`, string> {
  return {
    "--bg": theme.background,
    "--fg": theme.text,
    "--accent": brands.studios.palette.primary,
    "--accent-ink": brands.studios.palette.ink,
  };
}

